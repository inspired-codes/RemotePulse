using System;
using System.IO;
using System.Linq;
using System.Net.Http;
using System.Security.Cryptography;
using System.Text;
using Xunit;

namespace InspiredCodes.RemotePulse.Shared.Cryptography.Tests;

public class RequestSignerTests : IDisposable
{
    private readonly string _tempKeyPath;
    private readonly KeyPairManager _keyManager;

    public RequestSignerTests()
    {
        _tempKeyPath = Path.Combine(Path.GetTempPath(), $"signer_test_{Guid.NewGuid():N}.dat");
        _keyManager = new KeyPairManager(_tempKeyPath);
        _keyManager.GenerateAndSaveKeys();
    }

    public void Dispose()
    {
        _keyManager.Dispose();
        if (File.Exists(_tempKeyPath))
        {
            File.Delete(_tempKeyPath);
        }
    }

    [Theory]
    [InlineData("POST", "/api/telemetry/logs", "mach-1", "2026-09-15T00:00:00Z", "nonce-1", "POST:/api/telemetry/logs:mach-1:2026-09-15T00:00:00Z:nonce-1")]
    [InlineData("post", "api/commands/results", "mach-2", "2026-09-15T00:00:00Z", "nonce-2", "POST:/api/commands/results:mach-2:2026-09-15T00:00:00Z:nonce-2")]
    [InlineData("GET", "/api/commands/poll?timeout=25", "mach-3", "2026-09-15T00:00:00Z", "nonce-3", "GET:/api/commands/poll:mach-3:2026-09-15T00:00:00Z:nonce-3")]
    public void CreateSignatureMessage_ShouldFormatCorrectly(
        string method, string path, string clientId, string timestamp, string nonce, string expected)
    {
        string actual = RequestSigner.CreateSignatureMessage(method, path, clientId, timestamp, nonce);
        Assert.Equal(expected, actual);
    }

    [Fact]
    public void AddSignatureHeaders_ShouldAddValidVerifiableHeaders()
    {
        // Arrange
        const string clientId = "machine-test-123";
        using var request = new HttpRequestMessage(HttpMethod.Post, "https://hub.example.com/api/telemetry/logs");

        // Act
        RequestSigner.AddSignatureHeaders(request, _keyManager, clientId);

        // Assert
        Assert.True(request.Headers.Contains("X-Client-Id"));
        Assert.True(request.Headers.Contains("X-Timestamp"));
        Assert.True(request.Headers.Contains("X-Nonce"));
        Assert.True(request.Headers.Contains("X-Signature"));

        string actualClientId = request.Headers.GetValues("X-Client-Id").First();
        string timestamp = request.Headers.GetValues("X-Timestamp").First();
        string nonce = request.Headers.GetValues("X-Nonce").First();
        string signatureBase64 = request.Headers.GetValues("X-Signature").First();

        Assert.Equal(clientId, actualClientId);

        // Verify cryptographic signature exactly as HubServer does
        string expectedPath = "/api/telemetry/logs";
        string message = RequestSigner.CreateSignatureMessage("POST", expectedPath, clientId, timestamp, nonce);
        byte[] messageBytes = Encoding.UTF8.GetBytes(message);
        byte[] signatureBytes = Convert.FromBase64String(signatureBase64);

        using var ecdsa = ECDsa.Create();
        ecdsa.ImportSubjectPublicKeyInfo(Convert.FromBase64String(_keyManager.GetPublicKeyBase64()), out _);

        bool isValid = ecdsa.VerifyData(messageBytes, signatureBytes, HashAlgorithmName.SHA256, DSASignatureFormat.IeeeP1363FixedFieldConcatenation);
        Assert.True(isValid, "Cryptographic signature generated by RequestSigner must be valid according to Hub verification rules.");
    }
}
